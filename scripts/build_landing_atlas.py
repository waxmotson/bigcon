#!/usr/bin/env python3
"""Regenerate the landing page's exhibit atlas.

    python scripts/build_landing_atlas.py        (needs Pillow)

landing.html draws all 82 exhibits in 3D. Loading every full-size image would
cost ~25 MB, so this packs a 256x176 thumbnail of each one into a single
static/landing/atlas.webp and writes the tile order to static/landing/atlas.js.
Run it again whenever a node image in static/js/data.js is added or replaced;
tests/landing.test.mjs fails if a node is missing from the atlas (the page
itself falls back to a plain labelled card for a node it cannot find).
"""
import os
import re
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TILE_W, TILE_H, COLS = 256, 176, 8
PAPER = (244, 240, 230)

src = open(os.path.join(ROOT, 'static/js/data.js'), encoding='utf-8').read()
nodes = re.findall(r"\{id:'([^']+)',image:'\./([^']+)'[^\n]*?(?:shape:'([^']+)')?[^\n]*\n", src)
# shape sits after the image on the same line; re-read it per line to be safe
shapes = dict(re.findall(r"\{id:'([^']+)',[^\n]*?shape:'([^']+)'", src))
ids = [n[0] for n in nodes]
assert len(ids) == len(set(ids)) and len(ids) >= 70, 'unexpected node list: %d' % len(ids)

rows = -(-len(ids) // COLS)
sheet = Image.new('RGB', (COLS * TILE_W, rows * TILE_H), PAPER)
for i, (nid, rel, _) in enumerate(nodes):
    im = Image.open(os.path.join(ROOT, rel))
    if getattr(im, 'n_frames', 1) > 1:
        im.seek(0)
    im = im.convert('RGBA')
    has_alpha = im.getchannel('A').getextrema()[0] < 250
    tile = Image.new('RGBA', (TILE_W, TILE_H), PAPER + (255,))
    if has_alpha or shapes.get(nid) in ('logo', 'chart', 'bubble'):
        # logos, charts and cut-outs: fit the whole image on paper
        im.thumbnail((TILE_W - 16, TILE_H - 12), Image.LANCZOS)
        tile.alpha_composite(im, ((TILE_W - im.width) // 2, (TILE_H - im.height) // 2))
    else:
        # photographs: cover-crop; portraits keep the top of the frame (faces)
        s = max(TILE_W / im.width, TILE_H / im.height)
        im = im.resize((max(TILE_W, round(im.width * s)), max(TILE_H, round(im.height * s))), Image.LANCZOS)
        bias = 0.22 if shapes.get(nid) == 'photo' else 0.5
        x = (im.width - TILE_W) // 2
        y = round((im.height - TILE_H) * bias)
        tile.alpha_composite(im.crop((x, y, x + TILE_W, y + TILE_H)))
    sheet.paste(tile.convert('RGB'), ((i % COLS) * TILE_W, (i // COLS) * TILE_H))

out = os.path.join(ROOT, 'static/landing/atlas.webp')
sheet.save(out, 'WEBP', quality=82, method=6)
with open(os.path.join(ROOT, 'static/landing/atlas.js'), 'w', encoding='utf-8', newline='\n') as f:
    f.write("'use strict';\n/* Generated by scripts/build_landing_atlas.py — do not edit by hand. */\n")
    f.write('export const ATLAS={cols:%d,rows:%d,tileW:%d,tileH:%d,ids:%s};\n' % (
        COLS, rows, TILE_W, TILE_H, '[' + ','.join("'%s'" % i for i in ids) + ']'))
print('atlas: %d tiles, %dx%d, %d KB' % (len(ids), sheet.width, sheet.height, os.path.getsize(out) // 1024))
